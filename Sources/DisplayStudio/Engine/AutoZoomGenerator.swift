import Foundation
import CoreGraphics

public enum AutoZoomGenerator {
    public struct Configuration: Sendable {
        public var clusterWindowSeconds: TimeInterval
        public var leadInSeconds: TimeInterval
        public var holdTailSeconds: TimeInterval
        public var defaultZoomDepth: Double
        public var typingZoomDepth: Double
        public var transitionPreset: ZoomTransitionPreset

        public init(
            clusterWindowSeconds: TimeInterval = 2.4,
            leadInSeconds: TimeInterval = 0.28,
            holdTailSeconds: TimeInterval = 1.15,
            defaultZoomDepth: Double = 2.15,
            typingZoomDepth: Double = 2.35,
            transitionPreset: ZoomTransitionPreset = .quick
        ) {
            self.clusterWindowSeconds = clusterWindowSeconds
            self.leadInSeconds = leadInSeconds
            self.holdTailSeconds = holdTailSeconds
            self.defaultZoomDepth = defaultZoomDepth
            self.typingZoomDepth = typingZoomDepth
            self.transitionPreset = transitionPreset
        }
    }

    private struct ActivityAnchor {
        var timestamp: TimeInterval
        var position: CGPoint
        var isTyping: Bool
    }

    public static func generateZoomSegments(
        from telemetry: RecordingTelemetry,
        config: Configuration = Configuration()
    ) -> [ZoomSegment] {
        var anchors: [ActivityAnchor] = []

        for click in telemetry.clickEvents where click.phase == .down {
            anchors.append(ActivityAnchor(timestamp: click.timestamp, position: click.normalizedPos, isTyping: false))
        }

        for key in telemetry.keystrokeEvents where !key.isShortcut {
            anchors.append(ActivityAnchor(timestamp: key.timestamp, position: key.cursorNormalizedPos, isTyping: true))
        }

        anchors.sort { $0.timestamp < $1.timestamp }
        guard !anchors.isEmpty else { return [] }

        var segments: [ZoomSegment] = []
        var currentStart = max(0.0, anchors[0].timestamp - config.leadInSeconds)
        var currentEnd = min(telemetry.duration, anchors[0].timestamp + config.holdTailSeconds)
        var containsTyping = anchors[0].isTyping

        for anchor in anchors.dropFirst() {
            let proposedStart = max(0.0, anchor.timestamp - config.leadInSeconds)
            let proposedEnd = min(telemetry.duration, anchor.timestamp + config.holdTailSeconds)

            if proposedStart <= currentEnd + config.clusterWindowSeconds * 0.45 {
                currentEnd = max(currentEnd, proposedEnd)
                if anchor.isTyping { containsTyping = true }
            } else {
                segments.append(
                    ZoomSegment(
                        startTime: currentStart,
                        endTime: currentEnd,
                        zoomDepth: containsTyping ? config.typingZoomDepth : config.defaultZoomDepth,
                        mode: .followCursor,
                        transitionPreset: containsTyping ? .snappy : config.transitionPreset,
                        isAutoGenerated: true
                    )
                )
                currentStart = proposedStart
                currentEnd = proposedEnd
                containsTyping = anchor.isTyping
            }
        }

        segments.append(
            ZoomSegment(
                startTime: currentStart,
                endTime: currentEnd,
                zoomDepth: containsTyping ? config.typingZoomDepth : config.defaultZoomDepth,
                mode: .followCursor,
                transitionPreset: containsTyping ? .snappy : config.transitionPreset,
                isAutoGenerated: true
            )
        )

        return segments
    }
}
